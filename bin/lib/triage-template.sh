## Recommended Scope Subset

Step 4 of `source-triage.md`. **A slice is an ordering, not an exclusion.** The whole source is
always in scope; this section decides sequencing, not what gets dropped. Do not force POC framing
onto a project committed to a full migration — the decision (which capabilities go first) is the
same either way.

Two things this recommendation must NOT rest on alone: extraction cleanliness (the easiest
capability to automate is not automatically the right one to migrate first — ask the user about
business priority), and "everything is Ready, so do it all at once" (a large first slice needs
the same dependency and priority reasoning as a small one).

Format: capability -> verdict -> recommended for this slice (yes/no/deferred) -> why.

- {{EXAMPLE ROW — DELETE ME}} Order Management -> **Ready** -> yes -> highest business value, only two cross-capability dependencies
- {{EXAMPLE ROW — DELETE ME}} Reporting -> **Manual** -> deferred -> no extractor, and the SME wants the report set redesigned anyway

