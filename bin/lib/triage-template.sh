#!/usr/bin/env bash
# triage-template.sh — THE triage.md template. One copy, sourced by every writer.
#
# WHY THIS FILE EXISTS. Stage 0's gate (bin/gate-check.sh check_stage_0) has always REQUIRED
# triage.md, and until now nothing in the toolkit CREATED it. bin/init-project.sh scaffolded
# intake.md, PROJECT.md, CLAUDE.local.md, five agent stubs and index.html — and left the one
# Stage 0 artifact to be hand-typed from the "Output Template" fence at the bottom of
# skills/source-triage.md. The predictable happened, and it is measured:
#
#   ROUTING.md records source-triage.md reaching 1 of 6 wired projects. That one project
#   (VB-USI-main) hand-wrote its triage.md and it DRIFTED from the skill in the exact place
#   the skill shouts about: it invented a third extraction option, "Direct read
#   (recommended)", and concluded "Build no extractor" — while source-triage.md says in bold,
#   twice, that this is "a two-way call, not three-way" and "There is no manual-only path
#   anymore."
#
# An artifact nobody scaffolds gets re-derived from memory by whoever needs it, and memory is
# where the bolded warnings go missing. So the reuse-vs-build-new question below is pre-seeded
# as EXACTLY TWO rows with the third-option refusal written into the file itself: the guard
# lives where the author is typing, not three files away.
#
# THE SIGN-OFF LINE IS DELIBERATELY UNSIGNED. check_stage_0 requires a non-empty
# "Confirmed by:" INSIDE the "## Sign-off" section whose value contains no "[" — that second
# condition exists precisely because the unedited template line once passed a human-sign-off
# gate (see the comment at gate-check.sh:380). The template therefore ships the placeholder
# form "Confirmed by: [user] on [date]", and a freshly scaffolded triage.md FAILS Stage 0 by
# construction. Same discipline as intake.md's "_Not yet asked._" (bin/lib/intake-template.sh):
# a scaffold must never be able to certify the decision it exists to collect.
# tests/wave2/test-triage-report.sh pins that failure.
#
# CHANGING THE HEADINGS. "## Sign-off" and "Confirmed by:" are parsed by gate-check.sh; the
# section names mirror skills/source-triage.md's Output Template so the skill and the scaffold
# can be diffed by eye. Change one, change the other, and re-run tests/wave2/test-triage-report.sh
# and tests/wave2/test-stage-0*.sh.

# The full template body, exactly as init-project.sh writes it.
mxtk_triage_template() {
  cat <<'MXTK_TRIAGE_EOF'
<!-- MXTK-TRIAGE-STUB — generated by bin/init-project.sh from bin/lib/triage-template.sh.
     This marker plus any remaining {{PLACEHOLDER}} is how bin/sync-project.sh knows the file
     is still an untouched scaffold and may be refreshed. Fill the placeholders in and it is
     yours: sync will report it as edited and never overwrite it. -->

# Source Triage: {{APPLICATION_NAME}}

**Stage 0 — every entry mode.** This file is the Stage 0 deliverable named by
`skills/conversion-runbook.md` and gated by `bin/gate-check.sh <project> 0`. Fill it in by
following `skills/source-triage.md` — that skill is the reasoning, this file is only where the
answers land. Render it for review with `bin/triage-report.sh <project>` → `analysis/triage.html`.

**Never delete this file.** Whatever your entry mode, `gate-check.sh` would then report
*"triage.md not found"* — an unanswered gate rather than a settled one, and telling those two
apart is the only reason the gate exists. Until 2026-08-20 this header said the opposite
(*"requirements-driven or greenfield — delete this file"*) while the gate required it
unconditionally. Real sessions found the contradiction, correctly guessed that keeping the file
and marking rows `N/A` was the intent, and had to stop and ask. The instruction is now the one
they reverse-engineered.

**Stage 0 is the scope stage, not the extractor stage.** Only the *extraction* parts below need a
codebase. What varies by mode:

- **Migration** — everything applies.
- **Requirements-driven** — the Extraction Approach and Coverage Matrix rows are `N/A` **only if
  the corpus holds no extractable structure at all**. Open the folder before deciding: a DB schema
  or table dump, an ORM model, an OpenAPI/GraphQL contract, or entity/field tables inside a spec
  are extractable structure, and each gets a Coverage Matrix row and the two-way call above,
  exactly as a codebase would. Mark `N/A` on evidence (*"prose only — no schema anywhere in the
  corpus"*), never on the entry-mode label: "requirements-driven" says where the project came
  from, not what is in the folder. The Business Capability Map and the Recommended Scope Subset
  **still apply and still matter** — a document corpus has capabilities and a slice order exactly
  like a codebase does. Run `bin/source-sufficiency.sh` over the corpus.
- **Greenfield** — mark the extraction rows *and* the coverage matrix `N/A`. The scope subset is
  still the deliverable.

**Documents plus a database schema is not a documents-only source.** A table schema, an ORM model
or an OpenAPI contract is extractable structure and grades as such, whatever the markdown around
it looks like.

