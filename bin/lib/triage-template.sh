## Coverage Matrix

Step 3 of `source-triage.md`. One row per capability above. Answer, per capability: can it be
extracted automatically, does a mapper exist to turn that extraction into a BRD, and is the
output reliable enough to trust without heavy rework.

| Capability | Extractable? | Mapper -> BRD? | Reliable? | Verdict |
|---|---|---|---|---|
| {{EXAMPLE ROW — DELETE ME}} Order Management | Yes (Java extractor) | Yes (`domain-entity-mapper`) | Yes — sample checked | **Ready** |

**The five verdicts. Use these words; do not invent a sixth.** They mirror
`architecture-blueprint.md`'s fit-gap vocabulary on purpose, so the two documents stay legible
side by side.

- **Ready** — extract and map today, and trust the output.
- **Extract-only** — the JSON extracts fine, but no mapper exists for this shape yet.
- **Manual** — skip automation; this capability's BRD is written by hand.
- **Defer** — out of scope for this phase; revisit later.
- **Unknown** — cannot be assessed yet; needs a spike.

