## Extraction Approach

**This is a two-way call, not three-way, and it is the user's call, not the agent's.** Tick one
row. There is no third option and no manual-only path: field finding, recorded in
`source-triage.md`'s Core Principle, is that reading source without an extractor missed
information even on small, cleanly structured apps. A small app still gets an extractor; it just
means the extractor is small too. Inventing a third row here — "direct read", "no extractor
needed" — is the specific drift this scaffold exists to prevent (VB-USI, 2026).

| Decision | Chosen? | Which pipeline / what has to be built |
|---|---|---|
| **Reuse existing pipeline** | {{yes-or-no}} | {{outsystems / java-angular / node-express-react — and the layout-assumption check that says it actually fits, not just that the stack name matches}} |
| **Build new pipeline** | {{yes-or-no}} | {{what gets built or extended, and the ground truth it will be validated against per qa-loop-goal-pattern.md}} |

Reasoning: {{stack match, layout-assumption fit, effort tradeoff — the signal you put to the user}}

Who chose it, and when: {{name and date — the same decision is recorded in PROJECT.md}}

