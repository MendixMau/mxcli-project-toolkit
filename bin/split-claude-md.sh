#!/usr/bin/env bash
# split-claude-md.sh — move mxcli's bulk MDL/lint reference out of the project-root CLAUDE.md
# and into .claude/agent-reference/, where it loads only for the agent that needs it.
#
# WHY: mxcli scaffolds a full MDL command set, syntax reference, worked examples, lint-rule
# tables and best-practices scoring into CLAUDE.md. CLAUDE.md is auto-loaded into EVERY session
# and sits in the context prefix, so it is re-read on every API call for the whole session —
# including the many sessions that never write a line of MDL. Measured on WMS-Demo-main
# 2026-07-31: 494 of 699 lines, ~4.4k tokens, paid on every call.
#
# The content is not deleted. It moves to:
#   .claude/agent-reference/mdl-reference.md      <- mdl-agent's syntax authority
#   .claude/agent-reference/quality-reference.md  <- gate-agent's lint-rule authority
#
# WHY THERE and not .ai-context/skills/: `.ai-context/` is regenerated by mxcli upgrades and
# would lose the file. `.claude/agent-reference/` is owned by the project repo, and
# sync-project.sh does not touch it either (it only handles top-level agents/*.md).
#
# Heading-driven, not line-number driven, so it survives mxcli scaffold changes. Headings it
# does not find are skipped and reported — it never guesses a range.
#
# USAGE
#   split-claude-md.sh <project-root>            # dry run: report what would move
#   split-claude-md.sh <project-root> --apply    # do it (backs up CLAUDE.md first)
#
# After applying, point the agents at the new files — the toolkit's mdl-agent.md and
# gate-agent.md templates already reference them by path.

set -uo pipefail

ROOT="${1:-}"
APPLY=0
[ "${2:-}" = "--apply" ] && APPLY=1
[ -n "$ROOT" ] && [ -d "$ROOT" ] || { echo "usage: split-claude-md.sh <project-root> [--apply]" >&2; exit 1; }

CM="$ROOT/CLAUDE.md"
[ -f "$CM" ] || { echo "No CLAUDE.md at $CM" >&2; exit 1; }

# Sections to relocate, by exact H2 heading text. A section runs to the next H2 or EOF.
MDL_HEADS='MDL Commands by Domain
Script Validation (mxcli check)
MDL Syntax Quick Reference
MDL Script Files
Example: Create an Entity
Example: Create a Microflow
MDL Reference'

QUAL_HEADS='Linting
Best Practices Report'

export CM MDL_HEADS QUAL_HEADS APPLY ROOT
python3 - <<'PY'
import os, re, sys, shutil, datetime

cm    = os.environ['CM']; root = os.environ['ROOT']
apply_ = os.environ['APPLY'] == '1'
lines = open(cm, encoding='utf-8').read().split('\n')

# Map each H2 heading -> (start, end) line indices, end exclusive.
heads = [(i, l[3:].strip()) for i, l in enumerate(lines) if l.startswith('## ')]
spans = {}
for n, (i, title) in enumerate(heads):
    end = heads[n+1][0] if n+1 < len(heads) else len(lines)
    spans[title] = (i, end)

def collect(names):
    got, missing, idx = [], [], set()
    for nm in [x for x in names.split('\n') if x.strip()]:
        if nm in spans:
            a, b = spans[nm]
            got.append('\n'.join(lines[a:b]).rstrip())
            idx.update(range(a, b))
        else:
            missing.append(nm)
    return got, missing, idx

mdl,  miss_m, idx_m = collect(os.environ['MDL_HEADS'])
qual, miss_q, idx_q = collect(os.environ['QUAL_HEADS'])

moving = len(idx_m) + len(idx_q)
print(f"CLAUDE.md: {len(lines)} lines, ~{len(open(cm,'rb').read())//4} tokens")
print(f"  -> mdl-reference.md      : {len(mdl)} section(s), {len(idx_m)} lines")
print(f"  -> quality-reference.md  : {len(qual)} section(s), {len(idx_q)} lines")
print(f"  remaining in CLAUDE.md   : {len(lines)-moving} lines")
for m in miss_m + miss_q:
    print(f"  ! heading not found, skipped: {m!r}")
if not moving:
    print("Nothing to move — already split, or scaffold differs."); sys.exit(0)
if not apply_:
    print("\nDry run. Re-run with --apply to write."); sys.exit(0)

hdr = ("> Moved out of the project-root `CLAUDE.md` by `bin/split-claude-md.sh` on "
       f"{datetime.date.today()}.\n"
       "> It was auto-loaded into every session and re-read on every API call. It now loads\n"
       "> only when an agent opens it.\n>\n"
       "> **Not managed by mxcli.** `.ai-context/` is regenerated on upgrade; this path is not,\n"
       "> and `sync-project.sh` does not touch it either.\n")

outdir = os.path.join(root, '.claude', 'agent-reference')
os.makedirs(outdir, exist_ok=True)
shutil.copy2(cm, cm + '.bak-split')

if mdl:
    open(os.path.join(outdir,'mdl-reference.md'),'w',encoding='utf-8').write(
        "# MDL Authoring Reference\n\n"+hdr+"\n---\n\n"+"\n\n".join(mdl)+"\n")
if qual:
    open(os.path.join(outdir,'quality-reference.md'),'w',encoding='utf-8').write(
        "# Quality & Lint Reference\n\n"+hdr+"\n---\n\n"+"\n\n".join(qual)+"\n")

pointer = """## MDL & lint reference — NOT in this file, on purpose

The MDL command set, syntax reference, worked examples, lint rules and best-practices scoring
were moved out: they were auto-loaded into **every** session, including ones that never touch
MDL, and re-read on every API call. They now load only when needed:

| Need | Open |
|---|---|
| Writing or fixing MDL | `.claude/agent-reference/mdl-reference.md` |
| Digesting a gate/lint run | `.claude/agent-reference/quality-reference.md` |

`.ai-context/` is regenerated by mxcli upgrades; `.claude/agent-reference/` is not.

Read the reference when the task needs it — not to "have it available".
"""
kept, inserted = [], False
drop = idx_m | idx_q
for i, l in enumerate(lines):
    if i in drop:
        if not inserted:
            kept.append(pointer); inserted = True
        continue
    kept.append(l)
open(cm,'w',encoding='utf-8').write('\n'.join(kept).rstrip()+'\n')
print(f"\nApplied. Backup: {cm}.bak-split")
print(f"CLAUDE.md now ~{len(open(cm,'rb').read())//4} tokens")
PY
