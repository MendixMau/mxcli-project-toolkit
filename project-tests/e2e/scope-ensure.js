'use strict';
// scope-ensure.js — make sure .claude/loop/page-scope.json exists and is current before an audit reads it.
//
// WHY (speed experiment E2, 2026-10-29). page-audit.js and design-audit.js read the scope file and
// no MANDATORY step wrote it: on a finished app the first page-audit run was a FAULT with 0 pages
// until someone knew to run bin/page-scope.sh (2 s). A consumer with no producer is how
// design-audit.js sat installed and never ran for a whole build (CLAUDE.md "Shipping an
// instrument", rule 5). So the consumer is its own producer: when the file is missing, or older
// than the model (.mpr), it runs bin/page-scope.sh itself. page-scope.sh is facts-only, read-only
// on the model, and carries entries the file already has (orphans) forward, so re-running is safe.
//
// ensureScope({ scopeFile, mprPath, roots }) -> { ran: bool, ok: bool, note: string }
//   roots: directories that may hold bin/page-scope.sh (project root, and its parent for the
//   two-tree layout). A failed regeneration NEVER deletes or blanks an existing file: a stale
//   scope is returned as-is with ok=false and a note naming the failure, and the caller decides.
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

function mtime(p) { try { return fs.statSync(p).mtimeMs; } catch (e) { return 0; } }

function ensureScope({ scopeFile, mprPath, roots }) {
  const have = fs.existsSync(scopeFile);
  let why = '';
  if (!have) why = 'missing';
  else if (mprPath && mtime(mprPath) > mtime(scopeFile)) why = 'older than the model';
  if (!why) return { ran: false, ok: true, note: '' };
  const dir = (roots || []).find((r) => fs.existsSync(path.join(r, 'bin', 'page-scope.sh')));
  if (!dir) return { ran: false, ok: false, note: `scope ${why}; no bin/page-scope.sh under ${(roots || []).join(' or ')} to regenerate it (run sync-project.sh)` };
  // bash, not a bare wrapper name: Node resolves bash(.exe) on PATH on every platform the toolkit supports.
  const r = spawnSync('bash', [path.join(dir, 'bin', 'page-scope.sh')], {
    cwd: dir, encoding: 'utf8', timeout: 120000, env: Object.assign({}, process.env, { PROJECT_ROOT: dir }),
  });
  if (r.status === 0 && fs.existsSync(scopeFile)) return { ran: true, ok: true, note: `regenerated by bin/page-scope.sh (scope was ${why})` };
  const tail = String((r.stderr || '') + (r.stdout || '')).trim().split('\n').slice(-2).join(' / ').slice(0, 300);
  return { ran: true, ok: false, note: `bin/page-scope.sh failed (exit ${r.status === null ? 'signal/timeout' : r.status}; scope was ${why}): ${tail}` };
}

module.exports = { ensureScope };
