#!/usr/bin/env python3
"""jsregen.py: fixtures for the Studio Pro JS action comparison when NO EXTRA CODE block sits between the import list and
the function (so the text up to the first marker ends in 'export async function ...').

  jsregen.py pkg|regen|user OUTFILE

pkg   = the package copy: Studio Pro generated header, import "mx-global" and import { Big } from "big.js", the function.
regen = the app copy after a regeneration: the same user code, other generated header text, the imports in another form
        and order, without the Big import (Studio Pro adds it itself).
user  = regen with one USER CODE line changed.
"""
import sys

BODY = '''export async function Decode(base64) {
\t// BEGIN USER CODE
\treturn Base64.decode(base64);
\t// END USER CODE
}
'''
kind, out = sys.argv[1], sys.argv[2]
if kind == "pkg":
    t = ('import "mx-global";\nimport { Big } from "big.js";\nimport {Base64} from "js-base64";\n\n'
         '/**\n * @param {string} base64\n * @returns {Promise.<string>}\n */\n' + BODY)
elif kind == "regen":
    t = ('// This file was generated by Mendix Studio Pro.\n// WARNING: Only the following code will be retained.\n'
         "import { Base64 } from 'js-base64'\nimport \"mx-global\"\n\n"
         '/**\n * @param {string} base64 - the text\n */\n' + BODY).replace("\n", "\r\n")
else:
    t = ('import { Base64 } from "js-base64";\n\n' + BODY.replace("Base64.decode(base64)", "base64.trim()"))
open(out, "w", newline="").write(t)
